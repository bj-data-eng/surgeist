//! The source edition and adaptation notice are in `licenses/whatwg/NOTICE.md`.
//! The generator expands the heading group and preserves contextual index rows.

use crate::{DocumentString, Namespace, QualifiedName};

fn exact_string(value: &DocumentString, expected: &str) -> bool {
    value
        .code_units()
        .iter()
        .copied()
        .eq(expected.encode_utf16())
}

fn html_namespace(namespace: Option<&DocumentString>) -> bool {
    namespace.is_some_and(|uri| exact_string(uri, "http://www.w3.org/1999/xhtml"))
}

macro_rules! vocabulary {
    ($(#[$meta:meta])* $name:ident, $namespace:ident, [$($variant:ident => $local:literal),* $(,)?]) => {
        $(#[$meta])*
        #[derive(Clone, Copy, Debug, Eq, Hash, PartialEq)]
        pub enum $name {
            $(#[doc = concat!("The `", $local, "` name in the pinned inventory.")]
            $variant),*
        }

        impl $name {
            /// All individually named entries in this closed vocabulary.
            pub const ALL: &'static [Self] = &[$(Self::$variant),*];

            /// Returns the exact canonical local-name spelling.
            pub fn local_name(self) -> &'static str {
                match self { $(Self::$variant => $local),* }
            }

            /// Constructs the canonical expanded name without a prefix.
            pub fn qualified_name(self) -> QualifiedName {
                QualifiedName::new(Namespace::$namespace(), None, self.local_name())
            }
        }
    };
}

impl KnownHtmlElement {
    /// Recognizes an exact HTML namespace and local name, ignoring the prefix.
    ///
    /// Unknown, foreign, uppercase, and malformed names return `None`. The raw
    /// name remains unchanged; this is recognition, not HTML parser case folding.
    pub fn from_name(name: &(impl crate::HtmlNameInput + ?Sized)) -> Option<Self> {
        html_namespace(name.namespace_uri()).then(|| {
            Self::ALL
                .iter()
                .copied()
                .find(|known| exact_string(name.local_name(), known.local_name()))
        })?
    }

    /// Returns the source index row mentioning this element.
    ///
    /// The heading elements share their single original index row.
    pub fn inventory_row(self) -> &'static ElementInventoryRow {
        element_inventory()
            .iter()
            .find(|row| row.html_elements.contains(&self))
            .expect("generated element inventory includes every recognized element")
    }
}

impl KnownHtmlAttribute {
    /// Recognizes an exact no-namespace attribute name, ignoring the prefix.
    ///
    /// Recognition identifies the local spelling. Applicability and value
    /// semantics require the element-specific defining clause. A foreign or
    /// unknown raw attribute remains representable by [`crate::Attribute`].
    pub fn from_name(name: &(impl crate::HtmlNameInput + ?Sized)) -> Option<Self> {
        name.namespace_uri().is_none().then(|| {
            Self::ALL
                .iter()
                .copied()
                .find(|known| exact_string(name.local_name(), known.local_name()))
        })?
    }

    /// Iterates every contextual index row for this attribute spelling.
    ///
    /// Rows with the same local name remain distinct, including `for`, `type`,
    /// and `value`. The inventory does not select one row as a universal rule.
    pub fn inventory_rows(self) -> impl Iterator<Item = &'static AttributeInventoryRow> {
        attribute_inventory()
            .iter()
            .filter(move |row| row.attribute == self)
    }
}

