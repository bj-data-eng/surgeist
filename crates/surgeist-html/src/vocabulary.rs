/// One original row of the non-normative element index.
///
/// The two foreign root rows and autonomous custom-element family are retained
/// with empty [`Self::html_elements`] slices. Their printed names and linked
/// specifications retain the distinction from individually named HTML elements.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct ElementInventoryRow {
    row: u16,
    name: &'static str,
    html_elements: &'static [KnownHtmlElement],
    description: &'static str,
    categories: &'static str,
    parents: &'static str,
    children: &'static str,
    attributes: &'static str,
    interface: &'static str,
    references: &'static [&'static str],
}

impl ElementInventoryRow {
    /// Returns the original one-based index row, excluding the table header.
    pub fn row(self) -> u16 {
        self.row
    }
    /// Returns the printed name or family label, including the heading group.
    pub fn name(self) -> &'static str {
        self.name
    }
    /// Returns the individually named HTML elements mentioned by this row.
    pub fn html_elements(self) -> &'static [KnownHtmlElement] {
        self.html_elements
    }
    /// Returns the index's description; the defining clause remains authoritative.
    pub fn description(self) -> &'static str {
        self.description
    }
    /// Returns the printed categories, including conditional asterisks.
    pub fn categories(self) -> &'static str {
        self.categories
    }
    /// Returns the printed parent contexts, including conditional asterisks.
    pub fn parents(self) -> &'static str {
        self.parents
    }
    /// Returns the printed child summary, not a complete content-model validator.
    pub fn children(self) -> &'static str {
        self.children
    }
    /// Returns the printed attribute inventory summary.
    pub fn attributes(self) -> &'static str {
        self.attributes
    }
    /// Returns the source's interface label; no native interface is implied.
    pub fn interface(self) -> &'static str {
        self.interface
    }
    /// Returns linked element clauses, preserving separate foreign sources.
    pub fn references(self) -> &'static [&'static str] {
        self.references
    }
}

/// One contextual row of the non-normative attribute index.
///
/// Printed applicability and syntax retain the index's qualifications. The
/// known-element slice is a discovery aid, not a complete applicability decision:
/// input states, parent contexts, custom-element registration, and other defining
/// rules may matter. This record supplies no semantic defaults or execution owner.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct AttributeInventoryRow {
    row: u16,
    attribute: KnownHtmlAttribute,
    applicability: &'static str,
    html_elements: &'static [KnownHtmlElement],
    all_html_elements: bool,
    form_associated_custom_elements: bool,
    description: &'static str,
    value_syntax: &'static str,
    references: &'static [&'static str],
}

impl AttributeInventoryRow {
    /// Returns the original one-based index row, excluding the table header.
    pub fn row(self) -> u16 {
        self.row
    }
    /// Returns the recognized local-name identity for this row.
    pub fn attribute(self) -> KnownHtmlAttribute {
        self.attribute
    }
    /// Returns the exact printed applicability summary with whitespace collapsed.
    pub fn applicability(self) -> &'static str {
        self.applicability
    }
    /// Returns individually named HTML elements in the applicability cell.
    ///
    /// Parent/state qualifications remain in [`Self::applicability`] and linked
    /// defining clauses; this slice does not evaluate those qualifications.
    pub fn html_elements(self) -> &'static [KnownHtmlElement] {
        self.html_elements
    }
    /// Reports whether the index lists the open family of all HTML elements.
    pub fn all_html_elements(self) -> bool {
        self.all_html_elements
    }
    /// Reports whether the index lists form-associated custom elements.
    ///
    /// The index does not establish whether any particular raw name belongs to
    /// that family; registration and association belong to their semantic owner.
    pub fn form_associated_custom_elements(self) -> bool {
        self.form_associated_custom_elements
    }
    /// Returns the printed description, without asserting native execution.
    pub fn description(self) -> &'static str {
        self.description
    }
    /// Returns the printed value summary, not complete grammar or default rules.
    pub fn value_syntax(self) -> &'static str {
        self.value_syntax
    }
    /// Returns deduplicated linked clauses in source order.
    ///
    /// Local links are expanded to the immutable HTML snapshot. References to
    /// external specifications remain external; they are not HTML edition pins.
    pub fn references(self) -> &'static [&'static str] {
        self.references
    }
}

/// Returns all original element-index rows, including foreign and open families.
pub fn element_inventory() -> &'static [ElementInventoryRow] {
    ELEMENT_INVENTORY
}

/// Returns all contextual rows in the ordinary attribute index.
///
/// Event handlers, open attribute families, and obsolete attributes have separate
/// specification inventories and are not added to this closed index implicitly.
pub fn attribute_inventory() -> &'static [AttributeInventoryRow] {
    ATTRIBUTE_INVENTORY
}

