#!/usr/bin/env python3
"""Generate Text's raw Unicode width table using only the Python standard library."""

import argparse
import hashlib
from pathlib import Path
import re
import sys


CRATE = Path(__file__).resolve().parents[2]
INPUT = CRATE / "data/UnicodeData-width-18.0.0.txt"
OUTPUT = CRATE / "src/transform/width_data.rs"
SOURCE_SHA256 = "0736451de439ae7baf1425136617da495e09ee5afbe6e394374db7009ea08950"
RECORDS_SHA256 = "d202b05d03a4247fbe365bb5159a643639876415fcbab4c2765773f5f1f8ff40"
PAIRS_SHA256 = "523324ae4afd9cde0d257db25c803b85048adf4f699fe6ae4cda96e47b127a4d"
EXPECTED_COUNTS = {"<wide>": 104, "<narrow>": 122}
HEX_BMP = re.compile(r"[0-9A-F]{4}")


def scalar(value: str, line: int) -> int:
    if not HEX_BMP.fullmatch(value):
        raise ValueError(f"line {line}: expected one uppercase BMP code point")
    number = int(value, 16)
    if 0xD800 <= number <= 0xDFFF:
        raise ValueError(f"line {line}: surrogate is not a scalar")
    return number


def mappings(data: bytes) -> list[tuple[int, int]]:
    counts = dict.fromkeys(EXPECTED_COUNTS, 0)
    records = []
    pairs = {}
    destinations = set()
    previous = -1
    for line_number, line in enumerate(data.splitlines(keepends=True), 1):
        if line.startswith(b"#") or not line.strip():
            continue
        if not line.endswith(b"\n") or b"\r" in line:
            raise ValueError(f"line {line_number}: expected an untouched LF record")
        fields = line[:-1].decode("ascii").split(";")
        if len(fields) != 15:
            raise ValueError(f"line {line_number}: expected 15 UnicodeData fields")
        original = scalar(fields[0], line_number)
        if original <= previous:
            raise ValueError(f"line {line_number}: source records are not strictly ordered")
        previous = original
        decomposition = fields[5].split(" ")
        if len(decomposition) != 2 or decomposition[0] not in counts:
            raise ValueError(f"line {line_number}: expected a singleton wide/narrow mapping")
        tag, target = decomposition
        other = scalar(target, line_number)
        source, destination = (other, original) if tag == "<wide>" else (original, other)
        if source == destination:
            raise ValueError(f"line {line_number}: width mapping is an identity")
        if source in pairs or destination in destinations:
            raise ValueError(f"line {line_number}: duplicate mapping input or destination")
        counts[tag] += 1
        pairs[source] = destination
        destinations.add(destination)
        records.append(line)
    if counts != EXPECTED_COUNTS or len(pairs) != 226:
        raise ValueError(f"incomplete width relation: {counts}, {len(pairs)} pairs")
    if hashlib.sha256(b"".join(records)).hexdigest() != RECORDS_SHA256:
        raise ValueError("raw UnicodeData record checksum differs from the qualified excerpt")
    ordered = sorted(pairs.items())
    serialized = "".join(f"{source:04X};{target:04X}\n" for source, target in ordered)
    if hashlib.sha256(serialized.encode("ascii")).hexdigest() != PAIRS_SHA256:
        raise ValueError("directed width-pair checksum differs from the qualified relation")
    return ordered


def render(pairs: list[tuple[int, int]]) -> bytes:
    lines = [
        "// Generated by tools/full-width/generate.py; do not edit.",
        "// Copyright © 1991-2026 Unicode, Inc. SPDX-License-Identifier: Unicode-3.0",
        "// Source: https://www.unicode.org/Public/18.0.0/ucd/UnicodeData.txt",
        "// Input: data/UnicodeData-width-18.0.0.txt (untouched wide/narrow records).",
        f"// Complete source SHA256: {SOURCE_SHA256}",
        f"// Raw records SHA256: {RECORDS_SHA256}",
        f"// Directed pairs SHA256: {PAIRS_SHA256}",
        "// License and provenance: tools/full-width/README.md.",
        "",
        "pub(super) const MAPPINGS: &[(u32, u32)] = &[",
    ]
    lines.extend(f"    (0x{source:04x}, 0x{target:04x})," for source, target in pairs)
    lines.append("];\n")
    return "\n".join(lines).encode("utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare without writing any file")
    args = parser.parse_args()
    try:
        expected = render(mappings(INPUT.read_bytes()))
        if args.check:
            if OUTPUT.read_bytes() != expected:
                print(f"stale generated width table: {OUTPUT}", file=sys.stderr)
                return 1
            print("width table is current (226 mappings)")
        else:
            OUTPUT.write_bytes(expected)
            print("generated width table (226 mappings)")
    except (OSError, ValueError) as error:
        print(f"width generation failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
