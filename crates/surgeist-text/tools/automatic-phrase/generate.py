#!/usr/bin/env python3
"""Generate Text's private Japanese phrase tables with the Python standard library."""

import argparse
import hashlib
import json
from pathlib import Path
import sys

CRATE = Path(__file__).resolve().parents[2]
INPUT = CRATE / "data/budoux/0.9.3/ja.json"
OUTPUT = CRATE / "src/phrase/data.rs"
COMMIT = "25946bbbb271dc8a53bb5b04082c6859abc5c847"
SOURCE_SHA256 = "580db00a5e3e4a5b99b72cdea0db7ea70dac79599ce9d356d16bfdf0d92e7798"
GROUPS = [
    ("UW1", 1, 97), ("UW2", 1, 158), ("UW3", 1, 186),
    ("UW4", 1, 236), ("UW5", 1, 109), ("UW6", 1, 96),
    ("BW1", 2, 195), ("BW2", 2, 149), ("BW3", 2, 166),
    ("TW1", 3, 67), ("TW2", 3, 38), ("TW3", 3, 42), ("TW4", 3, 80),
]
I32_MIN, I32_MAX = -(2**31), 2**31 - 1


def unique(items):
    result = {}
    for key, value in items:
        if key in result:
            raise ValueError("duplicate JSON key")
        result[key] = value
    return result


def invalid_constant(value):
    raise ValueError(f"invalid JSON number: {value}")


def load_model(raw):
    model = json.loads(raw, object_pairs_hook=unique, parse_constant=invalid_constant)
    if type(model) is not dict or set(model) != {name for name, _, _ in GROUPS}:
        raise ValueError("unknown or missing feature group")
    for name, size, _ in GROUPS:
        entries = model[name]
        if type(entries) is not dict or not entries:
            raise ValueError(f"{name}: expected a nonempty feature object")
        for key, weight in entries.items():
            if len(key) != size or any(
                ord(cp) > 0xFFFF or 0xD800 <= ord(cp) <= 0xDFFF for cp in key
            ):
                raise ValueError(f"{name}: expected {size} BMP nonsurrogate positions")
            if type(weight) is not int or not -(2**15) <= weight < 2**15:
                raise ValueError(f"{name}: expected an i16 integer weight")
    weights = [weight for entries in model.values() for weight in entries.values()]
    total = sum(weights)
    absolute = sum(abs(weight) for weight in weights)
    low = -total + 2 * sum(min(0, *entries.values()) for entries in model.values())
    high = -total + 2 * sum(max(0, *entries.values()) for entries in model.values())
    if not (I32_MIN <= -absolute <= total <= absolute <= I32_MAX
            and I32_MIN <= low <= -total <= high <= I32_MAX):
        raise ValueError("model sums or doubled partial-score bounds exceed i32")
    return model


def pinned_model(raw):
    if len(raw) != 20190 or hashlib.sha256(raw).hexdigest() != SOURCE_SHA256:
        raise ValueError("model differs from the pinned BudouX 0.9.3 bytes")
    model = load_model(raw)
    if any(len(model[name]) != count for name, _, count in GROUPS):
        raise ValueError("pinned model feature counts differ")
    return model


def render(model):
    weights = [weight for entries in model.values() for weight in entries.values()]
    low = -sum(weights) + 2 * sum(min(0, *g.values()) for g in model.values())
    high = -sum(weights) + 2 * sum(max(0, *g.values()) for g in model.values())
    lines = [
        "// Generated by tools/automatic-phrase/generate.py; do not edit.",
        "// Copyright 2021 Google LLC. SPDX-License-Identifier: Apache-2.0",
        "// Modified by Surgeist: sorted numeric feature arrays and doubled integer bias.",
        f"// BudouX 0.9.3, commit {COMMIT}.",
        f"// Original ja.json SHA256: {SOURCE_SHA256}",
        "// License: licenses/budoux/LICENSE; provenance: tools/automatic-phrase/README.md.",
        f"// Qualified doubled score and partial sums: [{low}, {high}].",
        "",
        f"pub(super) const BIAS: i32 = {-sum(weights)};",
    ]
    for name, size, _ in GROUPS:
        lines.extend(["", f"pub(super) const {name}: &[([u16; {size}], i16)] = &["])
        entries = sorted((tuple(map(ord, key)), weight) for key, weight in model[name].items())
        for key, weight in entries:
            values = ", ".join(f"0x{cp:04x}" for cp in key)
            lines.append(f"    ([{values}], {weight}),")
        lines.append("];")
    return ("\n".join(lines) + "\n").encode("utf-8")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare bytes without writing")
    args = parser.parse_args(argv)
    try:
        expected = render(pinned_model(INPUT.read_bytes()))
        if args.check:
            if OUTPUT.read_bytes() != expected:
                print(f"stale generated phrase table: {OUTPUT}", file=sys.stderr)
                return 1
            print("phrase table is current (13 groups, 1619 weights)")
        else:
            OUTPUT.write_bytes(expected)
            print("generated phrase table (13 groups, 1619 weights)")
    except (OSError, ValueError) as error:
        print(f"phrase generation failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
