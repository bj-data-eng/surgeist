//! Each input position is one decoded semantic code point, including an opaque
//! isolated UTF-16 surrogate value. Supplementary scalars occupy one position.
//! Cuts index these positions, not bytes or UTF-16 units. The consuming Text
//! phase owns declared-language admission, original correspondence and CSS
//! admissibility; these raw model proposals alone establish none of them.

use super::phrase_data;

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum PhraseError {
    InvalidData,
    Capacity,
}

struct Model<'a> {
    unigrams: [&'a [([u16; 1], i16)]; 6],
    bigrams: [&'a [([u16; 2], i16)]; 3],
    trigrams: [&'a [([u16; 3], i16)]; 4],
    bias: i32,
}

const JAPANESE: Model<'static> = Model {
    unigrams: [
        phrase_data::UW1,
        phrase_data::UW2,
        phrase_data::UW3,
        phrase_data::UW4,
        phrase_data::UW5,
        phrase_data::UW6,
    ],
    bigrams: [phrase_data::BW1, phrase_data::BW2, phrase_data::BW3],
    trigrams: [
        phrase_data::TW1,
        phrase_data::TW2,
        phrase_data::TW3,
        phrase_data::TW4,
    ],
    bias: phrase_data::BIAS,
};

/// Returns strictly increasing internal model cuts in decoded input positions.
pub(crate) fn boundaries(input: &[u32]) -> Result<Vec<usize>, PhraseError> {
    JAPANESE.boundaries(input)
}

fn weight<const N: usize>(table: &[([u16; N], i16)], input: &[u32], start: Option<usize>) -> i32 {
    let Some(start) = start else {
        return 0;
    };
    let Some(end) = start.checked_add(N) else {
        return 0;
    };
    let Some(window) = input.get(start..end) else {
        return 0;
    };
    let mut key = [0; N];
    for (slot, &cp) in key.iter_mut().zip(window) {
        let Ok(value) = u16::try_from(cp) else {
            return 0;
        };
        *slot = value;
    }
    table
        .binary_search_by_key(&key, |&(key, _)| key)
        .map_or(0, |index| i32::from(table[index].1))
}

impl Model<'_> {
    fn score(&self, input: &[u32], cut: usize) -> Result<i32, PhraseError> {
        let left3 = cut.checked_sub(3);
        let left2 = cut.checked_sub(2);
        let left1 = cut.checked_sub(1);
        let here = Some(cut);
        let starts = [
            left3,
            left2,
            left1,
            here,
            cut.checked_add(1),
            cut.checked_add(2),
        ];
        let mut total = self.bias;
        let mut add = |value: i32| -> Result<(), PhraseError> {
            total = total
                .checked_add(value.checked_mul(2).ok_or(PhraseError::InvalidData)?)
                .ok_or(PhraseError::InvalidData)?;
            Ok(())
        };
        for (table, start) in self.unigrams.iter().zip(starts) {
            add(weight(table, input, start))?;
        }
        for (table, start) in self.bigrams.iter().zip([left2, left1, here]) {
            add(weight(table, input, start))?;
        }
        for (table, start) in self.trigrams.iter().zip([left3, left2, left1, here]) {
            add(weight(table, input, start))?;
        }
        Ok(total)
    }

    fn boundaries(&self, input: &[u32]) -> Result<Vec<usize>, PhraseError> {
        let mut cuts = Vec::new();
        cuts.try_reserve_exact(input.len().saturating_sub(1))
            .map_err(|_| PhraseError::Capacity)?;
        for cut in 1..input.len() {
            if self.score(input, cut)? > 0 {
                cuts.push(cut);
            }
        }
        Ok(cuts)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const EMPTY: Model<'static> = Model {
        unigrams: [&[]; 6],
        bigrams: [&[]; 3],
        trigrams: [&[]; 4],
        bias: 0,
    };

    fn points(text: &str) -> Vec<u32> {
        text.chars().map(u32::from).collect()
    }

    fn marked(text: &str) -> (Vec<u32>, Vec<usize>) {
        let mut input = Vec::new();
        let mut expected = Vec::new();
        for cp in text.chars() {
            if cp == '▁' {
                expected.push(input.len());
            } else {
                input.push(u32::from(cp));
            }
        }
        (input, expected)
    }

    #[test]
    fn original_quality_rows_retain_independent_upstream_phrase_expectations() {
        // Original marked expectations, not outputs generated by this adapter.
        let rows = include_str!("../../data/budoux/0.9.3/ja.tsv");
        let mut count = 0;
        for line in rows
            .lines()
            .filter(|line| !line.is_empty() && !line.starts_with('#'))
        {
            let (label, phrases) = line.split_once('\t').unwrap();
            let (input, expected) = marked(phrases);
            assert_eq!(boundaries(&input).unwrap(), expected, "{label}: {phrases}");
            count += 1;
        }
        assert_eq!(count, 41);
    }

    #[test]
    fn published_and_paired_literals_match_original_phrase_expectations() {
        for phrases in [
            "今日は▁天気です。",
            "Google の▁使命は、▁世界中の▁情報を▁整理し、▁世界中の▁人が▁アクセスできて▁使えるように▁する▁ことです。",
        ] {
            let (input, expected) = marked(phrases);
            assert_eq!(boundaries(&input).unwrap(), expected, "{phrases}");
        }
        // Independently folded source-model contributions at cut 3:
        // UW1 今=134, UW3 は=4640, UW6 で=157; ten absent features.
        assert_eq!(JAPANESE.score(&points("今日は天気です。"), 3), Ok(6646));
    }

    #[test]
    fn all_thirteen_feature_windows_select_the_intended_internal_cut() {
        let input = points("abcdefg");
        let uni = [0x61, 0x62, 0x63, 0x64, 0x65, 0x66].map(|cp| [([cp], 4)]);
        let bi = [[0x62, 0x63], [0x63, 0x64], [0x64, 0x65]].map(|key| [(key, 4)]);
        let tri = [
            [0x61, 0x62, 0x63],
            [0x62, 0x63, 0x64],
            [0x63, 0x64, 0x65],
            [0x64, 0x65, 0x66],
        ]
        .map(|key| [(key, 4)]);
        for index in 0..13 {
            let mut model = Model { bias: -4, ..EMPTY };
            match index {
                0..=5 => model.unigrams[index] = &uni[index],
                6..=8 => model.bigrams[index - 6] = &bi[index - 6],
                _ => model.trigrams[index - 9] = &tri[index - 9],
            }
            assert_eq!(model.boundaries(&input), Ok(vec![3]), "feature {index}");
        }
    }

    #[test]
    fn short_input_guards_require_complete_feature_windows() {
        let expected = [
            vec![3],
            vec![2, 3],
            vec![1, 2, 3],
            vec![1, 2, 3],
            vec![1, 2],
            vec![1],
            vec![2, 3],
            vec![1, 2, 3],
            vec![1, 2],
            vec![3],
            vec![2, 3],
            vec![1, 2],
            vec![1],
        ];
        for (index, cuts) in expected.into_iter().enumerate() {
            let mut model = Model { bias: -1, ..EMPTY };
            match index {
                0..=5 => model.unigrams[index] = &[([0x61], 1)],
                6..=8 => model.bigrams[index - 6] = &[([0x61, 0x61], 1)],
                _ => model.trigrams[index - 9] = &[([0x61, 0x61, 0x61], 1)],
            }
            assert_eq!(
                model.boundaries(&points("aaaa")),
                Ok(cuts),
                "feature {index}"
            );
            assert_eq!(model.boundaries(&[]), Ok(vec![]));
            assert_eq!(model.boundaries(&[0x61]), Ok(vec![]));
        }
    }

    #[test]
    fn strict_sign_and_checked_accumulation_are_preserved() {
        let input = points("AB");
        assert_eq!(EMPTY.boundaries(&input), Ok(vec![]));
        let mut model = Model { bias: -4, ..EMPTY };
        model.unigrams[3] = &[([0x42], 4)];
        assert_eq!(model.boundaries(&input), Ok(vec![1]));
        model.bias = -8;
        assert_eq!(model.boundaries(&input), Ok(vec![]));
        model.bias = 4;
        model.unigrams[3] = &[([0x42], -4)];
        assert_eq!(model.boundaries(&input), Ok(vec![]));
        model.bias = i32::MAX;
        model.unigrams[3] = &[([0x42], 4)];
        assert_eq!(model.boundaries(&input), Err(PhraseError::InvalidData));
        model.bias = i32::MIN;
        model.unigrams[3] = &[([0x42], -4)];
        assert_eq!(model.boundaries(&input), Err(PhraseError::InvalidData));
    }

    #[test]
    fn supplementary_positions_follow_paired_character_semantics() {
        // These exact diagnostics distinguish the selected native inference
        // semantics from UTF-16 indexing; they are not linguistic-quality claims.
        for (text, expected) in [
            ("今😀日は天気です。", vec![1, 5]),
            ("今日😀は天気です。", vec![1, 5]),
            ("今😀日はとても良い天気です。", vec![1, 5, 8, 10]),
            ("今日😀はとても良い天気です。", vec![1, 5, 8, 10]),
        ] {
            let input = points(text);
            let cuts = boundaries(&input).unwrap();
            let offsets: Vec<_> = std::iter::once(0)
                .chain(text.chars().scan(0, |offset, cp| {
                    *offset += cp.len_utf16();
                    Some(*offset)
                }))
                .collect();
            assert_eq!(
                cuts.iter().map(|&cut| offsets[cut]).collect::<Vec<_>>(),
                expected,
                "{text}"
            );
            assert!(cuts.iter().all(|&cut| cut > 0 && cut < input.len()));
        }
        // A supplementary value must not be narrowed to its low 16 bits.
        let mut model = Model { bias: -4, ..EMPTY };
        model.unigrams[3] = &[([0xf600], 4)];
        assert_eq!(model.boundaries(&[0x41, 0x1f600]), Ok(vec![]));
    }

    #[test]
    fn isolated_units_stay_opaque_and_distinct_from_literal_replacement() {
        let mut model = Model { bias: -4, ..EMPTY };
        model.unigrams[3] = &[([0xfffd], 4)];
        assert_eq!(model.boundaries(&[0x41, 0xfffd]), Ok(vec![1]));
        for cp in [0xd800, 0xdc00] {
            assert_eq!(model.boundaries(&[0x41, cp]), Ok(vec![]));
        }
        // Insertion occupies exactly one context position, without deletion or repair.
        model.unigrams[3] = &[];
        model.bigrams[1] = &[([0x41, 0x42], 4)];
        assert_eq!(model.boundaries(&[0x41, 0x42]), Ok(vec![1]));
        assert_eq!(model.boundaries(&[0x41, 0xd800, 0x42]), Ok(vec![]));
        assert_eq!(model.boundaries(&[0x41, 0x1f600, 0x42]), Ok(vec![]));
    }
}
