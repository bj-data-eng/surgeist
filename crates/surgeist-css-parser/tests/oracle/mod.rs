//! The inputs of the cssparser oracle.
//!
//! Two sets, both fixed:
//!
//! - [`spec_inputs`]: texts written from the prose branches and worked examples
//!   of CSS Syntax 3 section 4 (pinned edition), at least one for every branch of
//!   4.3.1 to 4.3.15 and for section 3.3's replacements. They are chosen from
//!   the clauses, not from cssparser's behavior.
//! - [`generated_inputs`]: texts built from the case generator of the property
//!   tests (`tests/common/generate.rs`) with a fixed seed, so they include the
//!   escaped-block-punctuation alphabet.

use crate::common::generate::{ENTROPY_BYTES, ESCAPES, Entropy, generate};

/// The number of generated cases. The seed and the count are part of the table:
/// changing either changes which differences occur.
pub const GENERATED_CASES: usize = 4000;
pub const GENERATED_SEED: u64 = 0x1508_5a11_0001;

pub fn spec_inputs() -> Vec<String> {
    let mut inputs: Vec<String> = SPEC.iter().map(|text| (*text).to_owned()).collect();
    // The six escapes of punctuation (4.3.7) in each context that matters.
    for escape in ESCAPES {
        for template in [
            "a{@}", "a{b:c;@}", "@", "(@)", "[@]", "f(@)", "\"@\"", "url(@)", "#@", "@x", "x@",
        ] {
            inputs.push(template.replace('@', escape));
        }
    }
    inputs
}

pub fn generated_inputs() -> Vec<String> {
    let mut entropy = Entropy::new(GENERATED_SEED);
    (0..GENERATED_CASES)
        .map(|_| generate(&entropy.bytes(ENTROPY_BYTES)))
        .collect()
}

